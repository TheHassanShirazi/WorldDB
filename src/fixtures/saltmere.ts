/** Guards against typos in the fixture — cheap, and it has already caught some. */
export function validateFixture(): string[] {
  const problems: string[] = [];
  for (const r of RELATIONSHIPS) {
    if (!ENTRIES_BY_ID.has(r.from)) problems.push(`${r.id}: unknown from "${r.from}"`);
    if (!ENTRIES_BY_ID.has(r.to)) problems.push(`${r.id}: unknown to "${r.to}"`);
  }
  const seen = new Set<string>();
  for (const e of ENTRIES) {
    if (seen.has(e.id)) problems.push(`duplicate entry id "${e.id}"`);
    seen.add(e.id);
  }
  return problems;
}
